const ALL: Record<string, [string, string, string]> = { ...P, ...MORE };

const norm = (t: string) => t.trim().toLowerCase().replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, ' ');

const lookup = (t: string) => {
  const k = norm(t);
  return Object.prototype.hasOwnProperty.call(ALL, k) ? ALL[k] : undefined;
};

const INDEX: Record<Lang, 0 | 1 | 2 | null> = { en: null, hi: 0, te: 1, ta: 2 };

/** Trailing "...", "…", ":" and "?" stay as they are while the words inside are translated. */
const TAIL = /(\s*(?:\.{3}|…|:|\?|!|\.)?\s*)$/;

export const translatePhrase = (lang: Lang, text: string): string => {
  const idx = INDEX[lang];
  if (idx === null || !text) return text;
  const lead = text.match(/^\s*/)![0];
  const body = text.slice(lead.length);
  if (!body) return text;
  const direct = lookup(body);
  if (direct) return lead + direct[idx] + (body.match(/\s*$/)![0] || '');
  const tail = body.match(TAIL)![0];
  const core = tail ? body.slice(0, body.length - tail.length) : body;
  const hit = lookup(core);
  return hit ? lead + hit[idx] + tail : text;
};
